/* Macro Definitions */
#define TOTAL_MODULES 59 /* Total number of modules in the game */

/* Struct for Interaction with Code Modules */
struct module
{
	INTU8 weather;           /* 0 = None, 1 = Underwater specle,
	                          * 2 = Rain, 3 = Snow */
	INTU16 requireditems[4]; /* Required items for this module */
	INTU8 numrequireditems;  /* Number of required items */
	INTU8 modnum;            /* 0 = VehcilePtr, 1 = WeatherPtr, 2 = Effect1Ptr,
	                          * 3 = Effect2Ptr, 4 = Effect3Ptr, 5 = Baddie1Ptr,
	                          * 6 = Baddie2Ptr, 7 = Baddie3Ptr, 8 = Baddie4Ptr,
	                          * 9 = Baddie5Ptr, 10 = Baddie6Ptr,
	                          * 11 = Baddie7Ptr, 12 = Baddie8Ptr */
	INTU16 length;           /* Length of the blob in bytes */
	const INTU8 *base;       /* Pointer to the base of the blob */
	INTU16 overnum;          /* Number of overlay-bytes */
	const INTU16 *overpos;   /* Positions of overlay-bytes */
	const INTU8 *overval;    /* Values of overlay-bytes */
	const char *name;        /* Name for this module */
};

#ifdef EXTERNAL_MODULES
/*
 * Builder version: the code modules are not part of this program. The file named by the
 * environment variable TR3PCPSX_MODULES (made by the builder from the player's own TR3 disc)
 * holds them, already in this game version's form: u32 count, then per module u32 index
 * (into modblobs), u32 length and the bytes. Every module the level needs must be there.
 */
static int loadExternalModules(struct module *modblobs, struct module **modules)
{
	FILE *f;
	INTU32 count, index, length, k;
	INTU8 *data;
	INTU8 found[TOTAL_MODULES] = {0};
	int m;
	const char *path = getenv("TR3PCPSX_MODULES");
	
	if (path == NULL || (f = fopen(path, "rb")) == NULL)
	{
		return ERROR_MODULE_FILE;
	}
	if (fread(&count, 4, 1, f) != 1)
	{
		fclose(f);
		return ERROR_MODULE_FILE;
	}
	for (k = 0; k < count; ++k)
	{
		if (fread(&index, 4, 1, f) != 1 || fread(&length, 4, 1, f) != 1 || index >= TOTAL_MODULES)
		{
			fclose(f);
			return ERROR_MODULE_FILE;
		}
		data = malloc(length);
		if (data == NULL || fread(data, 1, length, f) != length)
		{
			free(data);
			fclose(f);
			return ERROR_MODULE_FILE;
		}
		modblobs[index].base = data;
		modblobs[index].length = (INTU16) length;
		modblobs[index].overnum = 0;
		found[index] = 1;
	}
	fclose(f);
	for (m = 0; m < 13; ++m)
	{
		if (modules[m] != NULL && !found[modules[m] - modblobs])
		{
			printf("Missing code module: %s\n", modules[m]->name);
			return ERROR_MODULE_FILE;
		}
	}
	return ERROR_NONE;
}
#endif


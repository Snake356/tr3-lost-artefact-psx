"""Makes the builder's code module data from tools/src/tr3pcpsx/mod/modblob.h and modules.c:

  tools/src/tr3pcpsx/mod/modblob_empty.h   modblob.h with every code byte set to 0 (sizes and overlay
                                           positions stay), for the converter built with -DEXTERNAL_MODULES
  tools/builder/modules.json               per game version and module (index into modblobs): the
                                           original level file on the TR3 disc holding the module, its
                                           offset, length and CRC32, plus the project's byte changes
                                           (CHANGES: the Reunion fusebox, the Highland dragon heads)

The module locations are searched in the TR3 disc images given (Redump zips), one per version.
Usage: make_module_table.py <version>=<image> [...]"""
import json
import os
import re
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.join(HERE, "..", "src", "tr3pcpsx", "mod")
sys.path.insert(0, HERE)
import inputs  # noqa: E402

CASES = {"FLAGS_LANGUAGE_US_11_12": ("us", "us_11"), "FLAGS_LANGUAGE_UK_REV1": ("ukrev", "uk_r1"),
         "FLAGS_LANGUAGE_DE_REV1": ("derev", "de_r1"), "FLAGS_LANGUAGE_FR_REV1": ("frrev", "fr_r1"),
         "FLAGS_LANGUAGE_IT_REV1": ("itrev", "it_r1"), "FLAGS_LANGUAGE_SP_REV1": ("sprev", "sp_r1"),
         "FLAGS_LANGUAGE_JP_JP": ("jp", "jp1"), "FLAGS_LANGUAGE_JP_EN": ("jp2", "jp2"),
         "FLAGS_LANGUAGE_ASIA_JP": ("as", "asia1"), "FLAGS_LANGUAGE_ASIA_EN": ("as2", "asia2"),
         # Rev 0 (first releases)
         "FLAGS_LANGUAGE_US_10": ("us10", "us_10"), "FLAGS_LANGUAGE_UK": ("uk", "uk"),
         "FLAGS_LANGUAGE_DE": ("de", "de"), "FLAGS_LANGUAGE_FR": ("fr", "fr"), "FLAGS_LANGUAGE_IT": ("it", "it"),
         "FLAGS_LANGUAGE_SP": ("sp", "sp")}
# the project's byte changes in modblob.h: module -> {position: (original byte, project byte)}
CHANGES = {
    "e3_fusebox": {360: (12, 7)},                  # the original compares CurrentLevel with 12
    # ControlFireHead's height test takes the mouth's y (sp+0x24) instead of the item's (the Gold dragon's mouth
    # is 1.6 blocks above its item, so Lara never burnt), -512..+768 as TRX's M_TestFireRange (from 1.0.8):
    # 'lw v0, 0x44(s0)' -> 'lw v0, 0x24(sp)', 'addiu t2, v0, -0x400' -> -0x200, 'addiu t3, v0, 0x100' -> 0x300
    "e1_firehead": {0x314: (0x44, 0x24), 0x316: (0x02, 0xA2), 0x317: (0x8E, 0x8F), 0x31D: (0xFC, 0xFE),
                    0x325: (0x01, 0x03)},
}
ARRAY = re.compile(r"const INTU(8|16) (\w+)\[(\d+)\] = \{([^}]*)\}")


def main(images):
    src = open(os.path.join(MOD, "modblob.h"), encoding="latin-1").read()
    arr = {m.group(2): [int(x, 0) for x in m.group(4).split(",") if x.strip()] for m in ARRAY.finditer(src)}
    # empty header: code bytes (module_base_*, overval_*) zero, positions kept
    def blank(m):
        if m.group(2).startswith(("module_base_", "overval_")):
            n = int(m.group(3))
            return f"const INTU{m.group(1)} {m.group(2)}[{n}] = {{" + ",".join(["0"] * n) + "}"
        return m.group(0)
    open(os.path.join(MOD, "modblob_empty.h"), "w", encoding="latin-1", newline="\n").write(
        "/* Generated by tools/builder/make_module_table.py: modblob.h without the code bytes. */\n" + ARRAY.sub(blank, src))
    # per version: index -> base array name
    mc = open(os.path.join(MOD, "modules.c"), encoding="latin-1").read()
    table = {}
    for case, (ver, tag) in CASES.items():
        body = mc[mc.index(f"case {case}:"):]
        body = body[:re.search(r"\n\t\tcase FLAGS_|\n\t}", body[5:]).start() + 5]
        idx = {int(i): name for i, name in re.findall(r"modblobs\[(\d+)\]\.base = module_base_(\w+);", body)}
        opos = {int(i): name for i, name in re.findall(r"modblobs\[(\d+)\]\.overpos = (\w+);", body)}
        oval = {int(i): name for i, name in re.findall(r"modblobs\[(\d+)\]\.overval = (\w+);", body)}
        if ver not in images:
            continue
        disc, _ = inputs.open_image(images[ver])
        files = {p: disc.file(p) for p in sorted(disc.files) if p.endswith(".PSX")}
        mods = {}
        for i, name in sorted(idx.items()):
            code = bytearray(arr["module_base_" + name])
            for p, v in zip(arr.get(opos.get(i), []), arr.get(oval.get(i), [])):   # as modules.c pairs them
                code[p] = v
            entry = None
            for p, data in files.items():
                k = data.find(bytes(code))
                if k >= 0:
                    entry = {"file": p, "offset": k, "length": len(code), "crc32": "%08x" % zlib.crc32(code)}
                    break
            if entry is None and name in CHANGES:
                orig = bytearray(code)
                for pos, (was, _) in CHANGES[name].items():
                    orig[pos] = was
                for p, data in files.items():
                    k = data.find(bytes(orig))
                    if k >= 0:
                        entry = {"file": p, "offset": k, "length": len(code), "crc32": "%08x" % zlib.crc32(orig),
                                 "change": {str(pos): now for pos, (_, now) in CHANGES[name].items()}}
                        break
            if entry:
                mods[str(i)] = dict(entry, name=name)
        table[ver] = mods
        print(f"{ver}: {len(mods)} of {len(idx)} modules found")
    old = json.load(open(os.path.join(HERE, "modules.json"))) if os.path.exists(os.path.join(HERE, "modules.json")) else {}
    old.update(table)                              # versions not searched this time stay
    json.dump(old, open(os.path.join(HERE, "modules.json"), "w"), indent=1)


if __name__ == "__main__":
    main(dict(a.split("=", 1) for a in sys.argv[1:]))
